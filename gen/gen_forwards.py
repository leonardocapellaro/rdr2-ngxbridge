#!/usr/bin/env python3
"""Generate typed forwarding exports for the RDR2 Vulkan-FG NGX bridge.

Source of truth: the *exact* OptiScaler tag the user runs (v0.9.4). We read the
game-facing NGX entry-point definitions straight from that tree via `git show`
(read-only) so the bridge's export surface is byte-for-byte what RDR2 resolves
from OptiScaler.asi today. Output is C++ source, compiled later by MinGW-w64.

Usage: gen_forwards.py <path-to-optiscaler-repo> <outdir>
"""
import re, subprocess, sys, os

FILES = [
    "OptiScaler/inputs/NVNGX.cpp",
    "OptiScaler/inputs/NVNGX_DLSS_Dx11.cpp",
    "OptiScaler/inputs/NVNGX_DLSS_Dx12.cpp",
    "OptiScaler/inputs/NVNGX_DLSS_Vk.cpp",
]

def git_show(repo, tag, path):
    return subprocess.check_output(["git", "-C", repo, "show", f"{tag}:{path}"]).decode("utf-8", "replace")

def extract(text):
    """Return list of (name, ret_type, params_text) for live NVSDK_NGX_API definitions."""
    out = []
    # definition starts at line-begin NVSDK_NGX_API, ends at the brace opening the body
    for m in re.finditer(r'(?m)^NVSDK_NGX_API\s+(?P<sig>[^;{]+?)\s*\{', text):
        sig = " ".join(m.group("sig").split())
        # split return type + name + args
        mm = re.match(r'(?P<ret>.+?)\s+(?P<name>NVSDK_NGX_\w+)\s*\((?P<args>.*)\)$', sig)
        if not mm:
            raise SystemExit(f"unparsed signature: {sig}")
        name = mm.group("name")
        if name.endswith("_Impl") and "PopulateParameters" not in name:
            continue
        out.append((name, mm.group("ret").strip(), mm.group("args").strip()))
    return out

def split_args(args):
    if not args:
        return []
    parts, depth, cur = [], 0, ""
    for ch in args:
        if ch in "(<":
            depth += 1
        elif ch in ")>":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur); cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur)
    return [" ".join(p.split()) for p in parts]

def split_type_name(arg):
    # last whitespace-separated token is the parameter name unless it is part of the
    # type (e.g. "unsigned int" has a space, but then the name follows it anyway)
    if arg.strip() in ("void",):  # C-style (void) parameter list
        return "void", ""
    toks = arg.rsplit(" ", 1)
    if len(toks) != 2:
        raise SystemExit(f"cannot split arg: {arg!r}")
    typ, name = toks[0].strip(), toks[1].strip()
    if not re.fullmatch(r"\w+", name):
        # e.g. "PFN_... (*cb)" form -> not used in NGX headers
        raise SystemExit(f"odd parameter name: {arg!r}")
    return typ, name

def main():
    repo, outdir = sys.argv[1], sys.argv[2]
    seen = {}
    order = []
    for f in FILES:
        text = git_show(repo, "v0.9.4", f)
        for name, ret, args in extract(text):
            if name in seen and seen[name] != (ret, args):
                raise SystemExit(f"conflicting definitions for {name}")
            if name not in seen:
                order.append(name)
            seen[name] = (ret, args)

    os.makedirs(outdir, exist_ok=True)
    typedefs = []
    fwd_decl = []
    fwd_impl = []
    names_tbl = []
    for name in sorted(order):
        ret, args = seen[name]
        pars = [split_type_name(a) for a in split_args(args)]
        pty = ", ".join(t for t, _ in pars if t != "void")
        typedefs.append(f"typedef {ret} (NGX_CC *PFX_{name})({pty});")
        fwd_decl.append(f"extern \"C\" __declspec(dllexport) {ret} NGX_CC {name}({args});")
        callargs = ", ".join(n for _, n in pars if n)
        mirror = [n for t, n in pars if t.endswith("NVSDK_NGX_Parameter*") and "const" not in t and n]
        fwd_impl.append(
            f'extern "C" __declspec(dllexport) {ret} NGX_CC {name}({args}) {{\n'
            f'    auto target = (PFX_{name})NgxResolve("{name}");\n'
            f'    if (!target) {{ NgxLogMissing("{name}"); return ({ret})NGX_Result_Fail; }}\n'
            + (f'    NgxMirrorEnsure({mirror[0]});\n' if mirror else '')
            + f'    return target({callargs});\n'
            "}\n"
        )
        names_tbl.append(f'    "{name}",')

    with open(os.path.join(outdir, "ngx_exports_gen.h"), "w") as fh:
        fh.write("// GENERATED by gen_forwards.py from OptiScaler v0.9.4 sources - do not edit.\n")
        fh.write("#pragma once\n")
        fh.write("\n// Function-pointer types, one per exported entry point\n")
        for t in typedefs:
            fh.write(t + "\n")
        fh.write("\n// Export declarations (exact v0.9.4 game-facing surface)\n")
        for d in fwd_decl:
            fh.write(d + "\n")
    with open(os.path.join(outdir, "ngx_exports_gen.cpp"), "w") as fh:
        fh.write("// GENERATED by gen_forwards.py from OptiScaler v0.9.4 sources - do not edit.\n")
        fh.write('#include "ngxapi.h"\n#include "forward.h"\n#include "ngx_exports_gen.h"\n\n')
        fh.write("static const char* kExportNames[] = {\n" + "\n".join(names_tbl) + "\n};\n")
        fh.write("const unsigned kExportCount = sizeof(kExportNames)/sizeof(kExportNames[0]);\n\n")
        for impl in fwd_impl:
            fh.write(impl + "\n")
    print(f"generated {len(order)} exports -> {outdir}")

if __name__ == "__main__":
    main()
